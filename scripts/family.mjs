/** Family API: build and check a product family over this brand checkout's baseline.
 *
 *   node scripts/family.mjs build <familyRoot>   write <id>.css, <id>.json, <id>.tokens.json, <id>_tokens.rs
 *   node scripts/family.mjs check <familyRoot>   fail on contract, baseline, drift or contrast problems
 *
 * <familyRoot> is any directory containing tokens/family.json, usually a `brand-<product>` repository.
 * The baseline, contract and contrast pairs come from the checkout this script belongs to, resolved
 * from the script's own location, so a copy vendored at vendor/brand/scripts/family.mjs uses exactly
 * the release recorded in vendor/brand/brand.lock.json. Node.js only; deterministic and offline. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { brandRoot, loadBaseline, familySource, renderKit, BASELINE_SOURCE } from './generate-tokens.mjs';
import { contrastChecks } from './validate-tokens.mjs';

export const FAMILY_SOURCE = 'tokens/family.json';

/** Name and release version of the brand checkout this script runs from. */
export function brandRelease(root = brandRoot) {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  if (typeof pkg.name !== 'string' || !/^\d+\.\d+\.\d+$/.test(pkg.version ?? '')) throw new Error(`${path.join(root, 'package.json')}: expected a name and an X.Y.Z version`);
  return { name: pkg.name, version: pkg.version };
}

export const expectedExtends = (baseline) => `${baseline.name} baseline ${baseline.version}`;

const readFamily = (familyRoot) => {
  const file = path.join(familyRoot, FAMILY_SOURCE);
  if (!fs.existsSync(file)) throw new Error(`${FAMILY_SOURCE} not found in ${familyRoot}`);
  try { return JSON.parse(fs.readFileSync(file, 'utf8')); }
  catch (error) { throw new Error(`${FAMILY_SOURCE}: ${error.message}`); }
};

/** Resolves and renders a family without writing anything. Throws on a contract or source violation.
 * Returns `{ id, files: [[name, text]], semantic, summary }`; names are relative to <familyRoot>/tokens/. */
export function renderFamily(familyRoot, { root = brandRoot } = {}) {
  const baseline = loadBaseline(root);
  const release = brandRelease(root);
  const family = readFamily(familyRoot);
  const source = familySource(family, baseline);
  // Relative paths only: the header must read the same on every machine and in every checkout.
  const provenance = `Generated by ${release.name} ${release.version} scripts/family.mjs from ${FAMILY_SOURCE} over ${BASELINE_SOURCE}`;
  const { files, summary } = renderKit(source, { stem: family.id, scope: family.id, baseline, provenance });
  const json = files.find(([name]) => name === `${family.id}.json`);
  return { id: family.id, files, semantic: JSON.parse(json[1]).semantic, summary };
}

/** Writes the four outputs into <familyRoot>/tokens/ after the whole family has validated. */
export function buildFamily(familyRoot, options) {
  const rendered = renderFamily(familyRoot, options);
  for (const [name, text] of rendered.files) fs.writeFileSync(path.join(familyRoot, 'tokens', name), text);
  const failed = contrastChecks(rendered.id, rendered.semantic).filter(check => !check.pass);
  return { ...rendered, written: rendered.files.map(([name]) => `tokens/${name}`), failed };
}

/** Every problem with a family, without writing: contract, `extends`, committed drift and contrast. */
export function checkFamily(familyRoot, { root = brandRoot } = {}) {
  const problems = [];
  let family;
  try { family = readFamily(familyRoot); }
  catch (error) { return { problems: [error.message], checks: 0 }; }
  const baseline = loadBaseline(root);
  const expected = expectedExtends(baseline);
  if (family?.extends !== expected) {
    const release = brandRelease(root);
    problems.push(`${FAMILY_SOURCE} extends ${JSON.stringify(family?.extends)}, but ${release.name} ${release.version} provides ${JSON.stringify(expected)}; review the baseline changes, then update extends`);
    return { problems, checks: 0 };
  }
  let rendered;
  try { rendered = renderFamily(familyRoot, { root }); }
  catch (error) { problems.push(`contract: ${error.message}`); return { problems, checks: 0 }; }
  for (const [name, text] of rendered.files) {
    const file = path.join(familyRoot, 'tokens', name);
    if (!fs.existsSync(file)) problems.push(`tokens/${name} is missing; run family.mjs build`);
    else if (fs.readFileSync(file, 'utf8') !== text) problems.push(`tokens/${name} differs from what this brand release generates; never hand-edit it, run family.mjs build`);
  }
  const checks = contrastChecks(rendered.id, rendered.semantic);
  for (const c of checks.filter(check => !check.pass)) problems.push(`contrast: ${c.mode} ${c.pair} is ${c.ratio}:1, below ${c.threshold}:1 (${c.kind})`);
  return { id: rendered.id, problems, checks: checks.length };
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url))) {
  const [command, familyRoot, ...rest] = process.argv.slice(2);
  if (!['build', 'check'].includes(command) || !familyRoot || rest.length) {
    console.error('Usage: family.mjs build <familyRoot> | family.mjs check <familyRoot>');
    process.exit(2);
  }
  const release = brandRelease();
  try {
    if (command === 'build') {
      const result = buildFamily(familyRoot);
      console.log(`Built ${result.written.join(', ')} with ${release.name} ${release.version}; ${result.summary}.`);
      if (result.failed.length) {
        for (const c of result.failed) console.error(`contrast: ${c.mode} ${c.pair} is ${c.ratio}:1, below ${c.threshold}:1 (${c.kind})`);
        console.error(`${result.failed.length} contrast pair(s) fail; family.mjs check will fail until the source is fixed.`);
        process.exitCode = 1;
      }
    } else {
      const result = checkFamily(familyRoot);
      if (result.problems.length) {
        for (const problem of result.problems) console.error(problem);
        console.error(`Family check failed with ${release.name} ${release.version}: ${result.problems.length} problem(s).`);
        process.exitCode = 1;
      } else console.log(`Family ${result.id} conforms to ${release.name} ${release.version}: contract, extends, generated outputs and ${result.checks} contrast pairs.`);
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
