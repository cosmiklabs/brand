import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {buildFamily, checkFamily, renderFamily, brandRelease} from '../scripts/family.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'asset-manifest.json'), 'utf8'));
const names = ['example.css', 'example.json', 'example.tokens.json', 'example_tokens.rs'];

/** A copy of the fictional fixture family, as a brand-<product> repository would hold it. */
function familyRepo(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'brand-family-test-'));
  t.after(() => fs.rmSync(dir, {recursive: true, force: true}));
  fs.mkdirSync(path.join(dir, 'tokens'));
  fs.copyFileSync(path.join(root, 'tests/fixtures/example/tokens/family.json'), path.join(dir, 'tokens/family.json'));
  const edit = mutate => {
    const file = path.join(dir, 'tokens/family.json');
    const value = JSON.parse(fs.readFileSync(file, 'utf8'));
    mutate(value);
    fs.writeFileSync(file, JSON.stringify(value, null, 2));
  };
  return {dir, edit};
}
const cli = (script, args, cwd) => spawnSync(process.execPath, [script, ...args], {encoding: 'utf8', cwd});

test('build writes the four outputs and check accepts them', t => {
  const f = familyRepo(t);
  const built = buildFamily(f.dir);
  assert.deepEqual(built.written.sort(), names.map(n => `tokens/${n}`).sort());
  assert.deepEqual(built.failed, []);
  const result = checkFamily(f.dir);
  assert.deepEqual(result.problems, []);
  assert.equal(result.id, 'example');
  assert.ok(result.checks > 100);
  const css = fs.readFileSync(path.join(f.dir, 'tokens/example.css'), 'utf8');
  assert.match(css, /^\/\* Cosmik · Example 0\.0\.0 — PROPOSED\./);
  assert.match(css, /\[data-family="example"\] \{/);
  assert.match(css, /--c-accent: light-dark\(/);
  assert.match(css, /--c-elevation-2-shadow: 0px 4px 12px 0px light-dark\(/);
});

test('generated headers name the brand release and use relative paths only', t => {
  const f = familyRepo(t);
  buildFamily(f.dir);
  const {name, version} = brandRelease();
  const provenance = `Generated by ${name} ${version} scripts/family.mjs from tokens/family.json over kits/cosmik/tokens/source.json`;
  for (const n of names) {
    const text = fs.readFileSync(path.join(f.dir, 'tokens', n), 'utf8');
    if (n !== 'example.json') assert.ok(text.includes(provenance), n);
    for (const absolute of [f.dir, root, os.tmpdir(), os.homedir()]) assert.equal(text.includes(absolute), false, `${n} leaks ${absolute}`);
  }
});

test('builds are deterministic', t => {
  const f = familyRepo(t);
  const first = renderFamily(f.dir).files;
  const second = renderFamily(f.dir).files;
  assert.deepEqual(first, second);
});

test('check fails when committed outputs drift, are hand-edited or are missing', t => {
  const f = familyRepo(t);
  buildFamily(f.dir);
  fs.appendFileSync(path.join(f.dir, 'tokens/example.css'), '/* tweak */\n');
  fs.unlinkSync(path.join(f.dir, 'tokens/example_tokens.rs'));
  const {problems} = checkFamily(f.dir);
  assert.ok(problems.some(p => /tokens\/example\.css differs/.test(p)), problems.join('\n'));
  assert.ok(problems.some(p => /tokens\/example_tokens\.rs is missing/.test(p)), problems.join('\n'));
  // A source change without a rebuild is drift too.
  buildFamily(f.dir);
  f.edit(s => { s.version = '0.0.1'; });
  assert.ok(checkFamily(f.dir).problems.some(p => /differs from what this brand release generates/.test(p)));
});

test('check fails when extends does not name this baseline', t => {
  const f = familyRepo(t);
  buildFamily(f.dir);
  f.edit(s => { s.extends = 'Cosmik baseline 0.6.0'; });
  const {problems} = checkFamily(f.dir);
  assert.equal(problems.length, 1);
  assert.match(problems[0], /extends "Cosmik baseline 0\.6\.0", but @cosmiklabs\/brand \d+\.\d+\.\d+ provides "Cosmik baseline \d+\.\d+\.\d+"/);
});

for (const [label, mutate, expected] of [
  ['a utility type override', s => { s.type = {control: {fontWeight: 700}}; }, /utility type/],
  ['a motion override', s => { s.motion = {duration: '0ms'}; }, /unsupported property motion/],
  ['a reused baseline primitive name', s => { s.primitives.black = '#111111'; }, /exists in the baseline/],
]) {
  test(`check reports ${label} as a contract violation`, t => {
    const f = familyRepo(t);
    buildFamily(f.dir);
    f.edit(mutate);
    const {problems} = checkFamily(f.dir);
    assert.equal(problems.length, 1);
    assert.match(problems[0], /^contract: Family example: /);
    assert.match(problems[0], expected);
  });
}

test('check and build report contrast failures for baseline and extension roles', t => {
  const f = familyRepo(t);
  f.edit(s => {
    s.primitives['example-dark-low'] = '#202020';
    s.semantic.dark['action-primary'] = 'example-dark-low';
    s.extensions.light.accent = 'paper';
  });
  const built = cli(path.join(root, 'scripts/family.mjs'), ['build', f.dir]);
  assert.equal(built.status, 1);
  assert.match(built.stderr, /contrast pair\(s\) fail/);
  assert.equal(fs.existsSync(path.join(f.dir, 'tokens/example.css')), true, 'outputs remain inspectable');
  const result = cli(path.join(root, 'scripts/family.mjs'), ['check', f.dir]);
  assert.equal(result.status, 1);
  assert.match(result.stderr, /contrast: dark action-primary-fg \/ action-primary is [\d.]+:1, below 4\.5:1 \(text\)/);
  assert.match(result.stderr, /contrast: dark action-primary \/ bg is [\d.]+:1, below 3:1 \(boundary\)/);
  assert.match(result.stderr, /contrast: light accent \/ bg is [\d.]+:1, below 3:1 \(boundary\)/);
});

test('a family may set its own glass roles, and the check proves them over each tone band', t => {
  const f = familyRepo(t);
  f.edit(s => {
    s.primitives['example-dark-glass'] = '#0A122099';
    s.semantic.dark.glass = 'example-dark-glass';
  });
  assert.deepEqual(buildFamily(f.dir).failed, []);
  assert.match(fs.readFileSync(path.join(f.dir, 'tokens/example.css'), 'utf8'), /--c-glass: light-dark\(var\(--c-primitive-glass-light\), var\(--c-primitive-example-dark-glass\)\);/);
  // Too clear a tint loses text contrast over its band, and a sheen must be translucent.
  f.edit(s => { s.primitives['example-dark-glass'] = '#0A122020'; });
  buildFamily(f.dir);
  const {problems} = checkFamily(f.dir);
  assert.ok(problems.some(p => /contrast: dark text \/ glass over backdrops of luminance 0\.00–0\.25 is [\d.]+:1, below 4\.5:1 \(text\)/.test(p)), problems.join('\n'));
  f.edit(s => {
    s.primitives['example-light-sheen'] = '#FFFFFF';
    s.semantic.light['glass-sheen'] = 'example-light-sheen';
  });
  assert.throws(() => checkFamily(f.dir), /light glass-sheen: expected a translucent #RRGGBBAA role/);
});

test('check explains a missing family source and the CLI rejects bad usage', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'brand-family-empty-'));
  t.after(() => fs.rmSync(dir, {recursive: true, force: true}));
  assert.match(checkFamily(dir).problems[0], /tokens\/family\.json not found/);
  assert.equal(cli(path.join(root, 'scripts/family.mjs'), ['publish', dir]).status, 2);
  assert.equal(cli(path.join(root, 'scripts/family.mjs'), ['check']).status, 2);
});

test('a vendored copy resolves the baseline beside itself, not the caller\'s', t => {
  const f = familyRepo(t);
  const vendor = path.join(f.dir, 'vendor/brand');
  for (const {path: file} of manifest.distribution.files) {
    fs.mkdirSync(path.dirname(path.join(vendor, file)), {recursive: true});
    fs.copyFileSync(path.join(root, file), path.join(vendor, file));
  }
  const script = path.join(vendor, 'scripts/family.mjs');
  // Run from an unrelated working directory with a relative family root.
  const elsewhere = path.dirname(f.dir);
  assert.equal(cli(script, ['build', path.relative(elsewhere, f.dir)], elsewhere).status, 0);
  const check = cli(script, ['check', '.'], f.dir);
  assert.equal(check.status, 0, check.stderr);
  for (const [name, text] of renderFamily(f.dir).files) assert.equal(fs.readFileSync(path.join(f.dir, 'tokens', name), 'utf8'), text, name);
  // Change only the vendored baseline: the vendored generator must follow it.
  const source = path.join(vendor, 'kits/cosmik/tokens/source.json');
  const baseline = JSON.parse(fs.readFileSync(source, 'utf8'));
  baseline.motion.duration = '200ms';
  fs.writeFileSync(source, JSON.stringify(baseline));
  assert.equal(cli(script, ['build', '.'], f.dir).status, 0);
  assert.equal(JSON.parse(fs.readFileSync(path.join(f.dir, 'tokens/example.json'), 'utf8')).native.motion.durationMs, 200);
});
